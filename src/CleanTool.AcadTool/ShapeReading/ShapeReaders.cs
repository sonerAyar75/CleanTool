using System.Diagnostics.CodeAnalysis;
using Autodesk.AutoCAD.DatabaseServices;
using CleanTool.AcadTool.Infrastructure;
using CleanTool.Core.Geometry;
using CleanTool.Core.Geometry.Shapes;

namespace CleanTool.AcadTool.ShapeReading;

/// <summary>
/// Converts an AutoCAD object into Core's IShape model (Adapter).
/// Supporting a new type = a new reader + one line in <see cref="ShapeReaderRegistry.CreateDefault"/>.
/// </summary>
internal interface IShapeReader
{
    /// <summary>ObjectARX class name (e.g. "AcDbLine"). Used to filter objects without opening them.</summary>
    string DxfClassName { get; }

    /// <summary>Reads the entity into a Core shape (WCS coordinates).</summary>
    /// <param name="entity">The entity, opened for read.</param>
    /// <param name="transaction">Used to open sub-objects such as vertices and attributes.</param>
    IShape Read(Entity entity, Transaction transaction);
}

/// <summary>LINE.</summary>
internal sealed class LineShapeReader : IShapeReader
{
    /// <inheritdoc/>
    public string DxfClassName => "AcDbLine";

    /// <inheritdoc/>
    public IShape Read(Entity entity, Transaction transaction)
    {
        var line = (Line)entity;
        return new LineShape(new Segment3(AcadSession.ToCore(line.StartPoint), AcadSession.ToCore(line.EndPoint)));
    }
}

/// <summary>CIRCLE.</summary>
internal sealed class CircleShapeReader : IShapeReader
{
    /// <inheritdoc/>
    public string DxfClassName => "AcDbCircle";

    /// <inheritdoc/>
    public IShape Read(Entity entity, Transaction transaction)
    {
        var circle = (Circle)entity;
        return new CircleShape(AcadSession.ToCore(circle.Center), circle.Radius);
    }
}

/// <summary>ARC, read as start, end and midpoint.</summary>
internal sealed class ArcShapeReader : IShapeReader
{
    /// <inheritdoc/>
    public string DxfClassName => "AcDbArc";

    /// <inheritdoc/>
    public IShape Read(Entity entity, Transaction transaction)
    {
        var arc = (Arc)entity;
        var mid = arc.GetPointAtParameter((arc.StartParam + arc.EndParam) / 2);

        return new ArcShape(
            AcadSession.ToCore(arc.Center),
            arc.Radius,
            AcadSession.ToCore(arc.StartPoint),
            AcadSession.ToCore(arc.EndPoint),
            AcadSession.ToCore(mid));
    }
}

/// <summary>LWPOLYLINE.</summary>
internal sealed class PolylineShapeReader : IShapeReader
{
    /// <inheritdoc/>
    public string DxfClassName => "AcDbPolyline";

    /// <inheritdoc/>
    public IShape Read(Entity entity, Transaction transaction)
    {
        var pl = (Polyline)entity;

        // A polyline with normal -Z (mirrored) has visually reversed bulges; normalize them relative to WCS.
        var bulgeSign = pl.Normal.Z < 0 ? -1.0 : 1.0;

        var vertices = new List<PolylineVertex>(pl.NumberOfVertices);
        for (var i = 0; i < pl.NumberOfVertices; i++)
        {
            vertices.Add(new PolylineVertex(AcadSession.ToCore(pl.GetPoint3dAt(i)), pl.GetBulgeAt(i) * bulgeSign));
        }

        return new PolylineShape(vertices, pl.Closed);
    }
}

/// <summary>
/// Old-style 2D POLYLINE (common in drawings that came from DXF). Read into the same model as LWPolylines,
/// so a 2D polyline overlapping an LWPolyline is found as a copy too.
/// Intermediate vertices generated by spline/curve fitting are skipped; only the real vertices are read.
/// </summary>
internal sealed class Polyline2dShapeReader : IShapeReader
{
    /// <inheritdoc/>
    public string DxfClassName => "AcDb2dPolyline";

    /// <inheritdoc/>
    public IShape Read(Entity entity, Transaction transaction)
    {
        var pl = (Polyline2d)entity;
        var bulgeSign = pl.Normal.Z < 0 ? -1.0 : 1.0;
        var vertices = new List<PolylineVertex>();

        foreach (ObjectId id in pl)
        {
            var vertex = (Vertex2d)transaction.GetObject(id, OpenMode.ForRead);
            if (vertex.VertexType == Vertex2dType.SplineFitVertex || vertex.VertexType == Vertex2dType.CurveFitVertex) continue;

            vertices.Add(new PolylineVertex(AcadSession.ToCore(pl.VertexPosition(vertex)), vertex.Bulge * bulgeSign));
        }

        return new PolylineShape(vertices, pl.Closed);
    }
}

/// <summary>3D POLYLINE. Its segments are always straight (bulge 0). Spline control vertices are skipped.</summary>
internal sealed class Polyline3dShapeReader : IShapeReader
{
    /// <inheritdoc/>
    public string DxfClassName => "AcDb3dPolyline";

    /// <inheritdoc/>
    public IShape Read(Entity entity, Transaction transaction)
    {
        var pl = (Polyline3d)entity;
        var vertices = new List<PolylineVertex>();

        foreach (ObjectId id in pl)
        {
            var vertex = (PolylineVertex3d)transaction.GetObject(id, OpenMode.ForRead);
            if (vertex.VertexType == Vertex3dType.ControlVertex) continue;

            vertices.Add(new PolylineVertex(AcadSession.ToCore(vertex.Position), 0));
        }

        return new PolylineShape(vertices, pl.Closed);
    }
}

/// <summary>
/// Block reference (INSERT). MINSERT is a separate class ("AcDbMInsertBlock") and is deliberately not read.
/// </summary>
internal sealed class BlockReferenceShapeReader : IShapeReader
{
    /// <inheritdoc/>
    public string DxfClassName => "AcDbBlockReference";

    /// <inheritdoc/>
    public IShape Read(Entity entity, Transaction transaction)
    {
        var block = (BlockReference)entity;
        var scale = block.ScaleFactors;

        var attributes = new List<string>();
        foreach (ObjectId id in block.AttributeCollection)
        {
            if (id.IsErased) continue;
            if (transaction.GetObject(id, OpenMode.ForRead) is AttributeReference attribute)
                attributes.Add($"{attribute.Tag}={attribute.TextString}");
        }
        attributes.Sort(StringComparer.Ordinal);

        return new BlockShape(
            // Effective definition: for a dynamic block, the *U copy that carries the parameter values.
            block.BlockTableRecord.Handle.Value.ToString("X"),
            AcadSession.ToCore(block.Position),
            block.Rotation,
            scale.X,
            scale.Y,
            scale.Z,
            new Point3(block.Normal.X, block.Normal.Y, block.Normal.Z),
            attributes);
    }
}

/// <summary>Maps ObjectARX class names to readers, so entities can be filtered without opening them.</summary>
internal sealed class ShapeReaderRegistry
{
    private readonly Dictionary<string, IShapeReader> _byClassName;

    /// <summary>Creates a registry from the given readers (one per class name).</summary>
    public ShapeReaderRegistry(IEnumerable<IShapeReader> readers)
    {
        _byClassName = readers.ToDictionary(r => r.DxfClassName, StringComparer.OrdinalIgnoreCase);
    }

    /// <summary>Readers for LINE, CIRCLE, ARC, LWPOLYLINE, 2D/3D POLYLINE and INSERT.</summary>
    public static ShapeReaderRegistry CreateDefault() => new(new IShapeReader[]
    {
        new LineShapeReader(),
        new CircleShapeReader(),
        new ArcShapeReader(),
        new PolylineShapeReader(),
        new Polyline2dShapeReader(),
        new Polyline3dShapeReader(),
        new BlockReferenceShapeReader()
    });

    public bool TryGet(ObjectId id, [MaybeNullWhen(false)] out IShapeReader reader) =>
        _byClassName.TryGetValue(id.ObjectClass.Name, out reader);
}
